function applyLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'en';
  const els = document.querySelectorAll('[data-i18n]');
  els.forEach(function(el) {
    const key = el.getAttribute('data-i18n');
    if (TRANSLATIONS[lang][key]) {
      el.textContent = TRANSLATIONS[lang][key];
    }
  });
  document.documentElement.lang = lang === 'hi' ? 'hi' : lang === 'ta' ? 'ta' : lang === 'te' ? 'te' : 'en';
  localStorage.setItem('tmLang', lang);
}

function initLanguageSwitcher() {
  var saved = localStorage.getItem('tmLang');
  if (saved && TRANSLATIONS[saved]) applyLanguage(saved);

  var langOptions = document.querySelectorAll('.languageoption a');
  var langLabel = document.querySelector('.langselected p');
  var langMap = { 'english': 'en', 'hindi': 'hi', 'tamil': 'ta', 'telugu': 'te' };
  var labelMap = { 'en': 'ENGLISH', 'hi': 'HINDI', 'ta': 'TAMIL', 'te': 'TELUGU' };

  if (saved && labelMap[saved] && langLabel) {
    langLabel.textContent = labelMap[saved];
  }

  langOptions.forEach(function(opt) {
    opt.addEventListener('click', function(e) {
      e.preventDefault();
      var lang = langMap[opt.textContent.trim().toLowerCase()];
      if (lang) {
        applyLanguage(lang);
        if (langLabel) langLabel.textContent = labelMap[lang];
      }
    });
  });
}

document.addEventListener('DOMContentLoaded', initLanguageSwitcher);
